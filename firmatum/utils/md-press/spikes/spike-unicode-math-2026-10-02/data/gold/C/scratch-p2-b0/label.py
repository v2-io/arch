def apply(text, edits):
    out, cur = [], 0
    for old, new in edits:
        j = text.find(old, cur)
        if j < 0:
            raise ValueError(f'not found from {cur}: {old!r}')
        out.append(text[cur:j]); out.append(new); cur = j + len(old)
    out.append(text[cur:])
    return ''.join(out)

items = [json.loads(l) for l in open(TASKS)]
missing = [d['gid'] for d in items if d['gid'] not in L]
extra = set(L) - {d['gid'] for d in items}
assert not missing and not extra, (missing, extra)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w') as f:
    for d in items:
        edits, conf, note = L[d['gid']]
        gold = apply(d['text'], edits)
        f.write(json.dumps({'gid': d['gid'], 'gold': gold, 'conf': conf, 'note': note}, ensure_ascii=False) + '\n')
print('wrote', OUT, len(items))
