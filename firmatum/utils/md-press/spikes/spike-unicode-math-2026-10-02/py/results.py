"""Results tables for README: every set x system, verdict counts. Writes results.md."""
import json, sys, collections, importlib.util
sys.path.insert(0, 'py')
import evaluate, evaluate_c, atoms, score
LADDER = ['exact', 'equivalent', 'degraded', 'over', 'wrong']

def frozen(nm):
    return evaluate_c.load_frozen(nm)

def row(name, c):
    n = sum(c.values())
    ok = c['exact'] + c['equivalent']
    return f"| {name} | {n} | {c['exact']} ({c['exact']/n:.0%}) | {ok} ({ok/n:.1%}) | {c['degraded']} | {c['over']} | {c['wrong']} | {(c['over']+c['wrong'])/n:.1%} |"

out = []
hdr = "| system | n | exact | exact+equivalent | degraded | over | wrong | wrong+over |\n|---|---|---|---|---|---|---|---|"
# A / B
items, passes = score.load_gold(evaluate.BASE)
mods = {v: frozen(f'umath_{v}') for v in ('v1', 'v2', 'v3', 'v4')}
for st in ('A', 'B'):
    sel = {g: it for g, it in items.items() if g[0] == st and g in passes[1] and g in passes[2]}
    out.append(f"\n### Set {st}\n\n{hdr}")
    systems = [('leave as written', {g: it['text'] for g, it in sel.items()})]
    for nm in (('llama', 'muse') if st == 'A' else ('llama',)):
        systems.append((nm + ' (as md-press writes it)', evaluate.system_outputs(nm, sel)))
    for v, mm in mods.items():
        systems.append((f'det {v}', {g: mm.convert(it['text'])[0] for g, it in sel.items()}))
    for nm, outs in systems:
        c = collections.Counter()
        for g, it in sel.items():
            c[evaluate.verdict2(it['text'], [passes[1][g]['gold'], passes[2][g]['gold']], outs[g])[0]] += 1
        out.append(row(nm, c))
# C / D by kind
for st in ('C', 'D'):
    evaluate_c.SET = st
    try:
        it2, P = evaluate_c.gold()
    except Exception:
        continue
    both = [g for g in it2 if g in P[1] and g in P[2]]
    if not both:
        continue
    out.append(f"\n### Set {st} (by kind)\n")
    kinds = sorted(set(it2[g]['kind'] for g in both))
    for kind in kinds + ['ALL']:
        gs = [g for g in both if kind == 'ALL' or it2[g]['kind'] == kind]
        out.append(f"\n**{st} · {kind}**\n\n{hdr}")
        for nm, fn in [('leave as written', lambda t: t)] + [(f'det {v}', (lambda mm: lambda t: mm.convert(t)[0])(mm)) for v, mm in mods.items()]:
            c = collections.Counter(evaluate_c.best(fn(it2[g]['text']), [P[1][g]['gold'], P[2][g]['gold']]) for g in gs)
            out.append(row(nm, c))
open('results.md', 'w').write('# Results tables (generated by py/results.py)\n' + '\n'.join(out) + '\n')
print('\n'.join(out))
