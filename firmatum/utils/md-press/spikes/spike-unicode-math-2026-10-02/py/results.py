"""Results tables (results.md). Scorer v2 (py/atoms.py) unless noted; scorer v1
(py/atoms_v1.py) is the ladder used before de-novo feedback 1."""
import json, sys, collections, importlib
sys.path.insert(0, 'py')
import evaluate, evaluate_c, score
import atoms, atoms_v1
LADDER = ['exact', 'equivalent', 'degraded', 'over', 'wrong']
VERS = ('v1', 'v2', 'v3', 'v4', 'v6', 'v7')
mods = {v: evaluate_c.load_frozen(f'umath_{v}') for v in VERS}
HDR = "| system | n | exact | exact+equivalent | degraded | over | wrong | wrong+over | changed | wrong+over among changed |\n|---|---|---|---|---|---|---|---|---|---|"


def verdict(scorer, out, golds, worst=False):
    vs = [scorer.compare(out, g)[0] for g in golds]
    return (max if worst else min)(vs, key=LADDER.index)


def row(name, items, outs, golds, scorer=atoms, worst=False):
    c = collections.Counter(); ch = bad = 0
    for g in items:
        v = verdict(scorer, outs[g], golds[g], worst); c[v] += 1
        if outs[g] != items[g]:
            ch += 1; bad += v in ('wrong', 'over')
    n = sum(c.values()); ok = c['exact'] + c['equivalent']
    return (f"| {name} | {n} | {c['exact']} ({c['exact']/n:.0%}) | {ok} ({ok/n:.1%}) | {c['degraded']} | {c['over']} | "
            f"{c['wrong']} | {(c['over']+c['wrong'])/n:.1%} | {ch} | {bad/ch:.1%} |" if ch else
            f"| {name} | {n} | {c['exact']} | {ok} ({ok/n:.1%}) | {c['degraded']} | {c['over']} | {c['wrong']} | {(c['over']+c['wrong'])/n:.1%} | 0 | — |")


out = []
items, passes = score.load_gold(evaluate.BASE)
for st in ('A', 'B'):
    sel = {g: it['text'] for g, it in items.items() if g[0] == st and g in passes[1] and g in passes[2]}
    golds = {g: [passes[1][g]['gold'], passes[2][g]['gold']] for g in sel}
    out.append(f"\n### Set {st}\n\n{HDR}")
    out.append(row('leave as written', sel, sel, golds))
    for nm in (('llama', 'muse') if st == 'A' else ('llama',)):
        o = evaluate.system_outputs(nm, {g: items[g] for g in sel})
        out.append(row(nm + ' (md-press pieces + gates)', sel, o, golds))
    for v in VERS:
        out.append(row(f'det {v}', sel, {g: mods[v].convert(t)[0] for g, t in sel.items()}, golds))
for st in ('C', 'D'):
    evaluate_c.SET = st
    it2, P = evaluate_c.gold()
    both = [g for g in it2 if g in P[1] and g in P[2]]
    out.append(f"\n### Set {st} (by kind)\n")
    for kind in sorted(set(it2[g]['kind'] for g in both)) + ['ALL']:
        sel = {g: it2[g]['text'] for g in both if kind == 'ALL' or it2[g]['kind'] == kind}
        golds = {g: [P[1][g]['gold'], P[2][g]['gold']] for g in sel}
        out.append(f"\n**{st} · {kind}**\n\n{HDR}")
        out.append(row('leave as written', sel, sel, golds))
        if st == 'D' and kind == 'line':
            L = {json.loads(l)['gid']: json.loads(l)['out'] for l in open('data/llama-D-lines.jsonl')}
            out.append(row('llama3.2:3b (md-press pieces + gates)', sel, L, golds))
        for v in VERS:
            out.append(row(f'det {v}', sel, {g: mods[v].convert(t)[0] for g, t in sel.items()}, golds))
        if st == 'D' and kind == 'line':
            o7 = {g: mods['v7'].convert(t)[0] for g, t in sel.items()}
            o4 = {g: mods['v4'].convert(t)[0] for g, t in sel.items()}
            out.append(row('det v4, scored with scorer v1 (pre-feedback)', sel, o4, golds, atoms_v1))
            out.append(row('det v4, scored against the WORSE labeler', sel, o4, golds, worst=True))
            atoms.STRICT_SLASH = True
            out.append(row('det v4, strict slash (merged `α/β` = wrong)', sel, o4, golds))
            out.append(row('det v7, strict slash', sel, o7, golds))
            out.append(row('llama3.2:3b, strict slash', sel, L, golds))
            atoms.STRICT_SLASH = False
# labeler agreement under scorer v2
out.append("\n### Labeler vs labeler (scorer v2): pass 1 scored against pass 2\n\n| set | n | exact+equivalent |\n|---|---|---|")
ag = [atoms.compare(passes[1][g]['gold'], passes[2][g]['gold'])[0] in ('exact', 'equivalent') for g in items if g in passes[1] and g in passes[2]]
out.append(f"| A+B | {len(ag)} | {sum(ag)} ({sum(ag)/len(ag):.1%}) |")
for st in ('C', 'D'):
    evaluate_c.SET = st; it2, P = evaluate_c.gold()
    for kind in ('line', None):
        gs = [g for g in it2 if g in P[1] and g in P[2] and (kind is None or it2[g]['kind'] == kind)]
        if not gs:
            continue
        a = [atoms.compare(P[1][g]['gold'], P[2][g]['gold'])[0] in ('exact', 'equivalent') for g in gs]
        out.append(f"| {st}{' lines' if kind else ''} | {len(a)} | {sum(a)} ({sum(a)/len(a):.1%}) |")
open('results.md', 'w').write('# Results tables (generated by py/results.py; scorer v2 unless noted)\n'
                              '\nColumns "changed" and "wrong+over among changed" count items the system altered and the share of those it got wrong or over-converted.\n'
                              + '\n'.join(out) + '\n')
print('\n'.join(out))
